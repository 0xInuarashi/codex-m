#!/usr/bin/env python3
"""Adapt upstream's installer; fail visibly when its integration points change."""
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = (root / 'scripts/install/install.sh').read_text()
replacements = {
    'DAEMON_ONLY="${CODEX_INSTALL_DAEMON_ONLY:-0}"': 'DAEMON_ONLY="0"',
    'DEFAULT_PREFER_RELEASES_OPENAI_COM="true"': 'DEFAULT_PREFER_RELEASES_OPENAI_COM="false"',
    'PREFER_RELEASES_OPENAI_COM="${CODEX_INSTALLER_USE_RELEASES_OPENAI_COM:-$DEFAULT_PREFER_RELEASES_OPENAI_COM}"': 'PREFER_RELEASES_OPENAI_COM="false"',
    'BIN_PATH="$BIN_DIR/codex"': 'BIN_PATH="$BIN_DIR/codex-m"',
    'CODE_MODE_HOST_BIN_PATH="$BIN_DIR/codex-code-mode-host"': 'CODE_MODE_HOST_BIN_PATH="$BIN_DIR/codex-m-code-mode-host"',
    'STANDALONE_ROOT="$CODEX_HOME_DIR/packages/standalone"': 'STANDALONE_ROOT="$CODEX_HOME_DIR/packages/codex-m"',
    'github.com/openai/codex/releases/': 'github.com/0xInuarashi/codex-m/releases/',
    'api.github.com/repos/openai/codex/releases/': 'api.github.com/repos/0xInuarashi/codex-m/releases/',
    '-beta(\\.[0-9]+)?)?': '-beta(\\.[0-9]+)?|-codex-m\\.[0-9]+)?',
    'command -v codex ': 'command -v codex-m ',
    'tmp_link="$BIN_DIR/.codex.$$"': 'tmp_link="$BIN_DIR/.codex-m.$$"',
    '$CODEX_HOME_DIR/app-server-daemon/': '$CODEX_HOME_DIR/codex-m-daemon/',
    '&& codex"': '&& codex-m"',
    'terminal: codex"': 'terminal: codex-m"',
    'run: codex"': 'run: codex-m"',
}
for old, new in replacements.items():
    if old not in source:
        raise SystemExit(f'Upstream installer changed: missing {old!r}')
    source = source.replace(old, new)
# A fork must never offer to uninstall an official package-manager installation.
source = source.replace('  detect_conflicting_install\n', '  : # codex-m coexists with the official CLI\n')
source = source.replace('resolve_release\nrelease_name=', '''if [ "$os-$arch" != "linux-x86_64" ]; then
  echo "codex-m currently publishes Linux x86_64 binaries only." >&2
  exit 1
fi
resolve_release
release_name=''')
source = source.replace('set -eu\n', '# Generated by scripts/generate-codex-m-installer.py from upstream.\nset -eu\n', 1)
output = root / 'install.sh'
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != source:
        raise SystemExit('Run python3 scripts/generate-codex-m-installer.py')
else:
    output.write_text(source)
    output.chmod(0o755)
